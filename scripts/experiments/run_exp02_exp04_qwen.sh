#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ONE_MODEL_SH="${SCRIPT_DIR}/run_exp02_exp04_model.sh"

MODEL_ID="${MODEL_ID:-/path/to/models/tokyotech-llm/Qwen3-Swallow-8B-SFT-v0.2}"
MODEL_TAG="${MODEL_TAG:-qwen3}"
TRAIN_CUDA_VISIBLE_DEVICES="${TRAIN_CUDA_VISIBLE_DEVICES:-1}"
INFER_CUDA_VISIBLE_DEVICES="${INFER_CUDA_VISIBLE_DEVICES:-${TRAIN_CUDA_VISIBLE_DEVICES}}"
INFER_NUM_SHARDS="${INFER_NUM_SHARDS:-8}"
RUN_BASE_DIR="${RUN_BASE_DIR:-/path/to/results/sft}"
EXP02_MAX_NEW_TOKENS="${EXP02_MAX_NEW_TOKENS:-3072}"
EXP04_MAX_NEW_TOKENS="${EXP04_MAX_NEW_TOKENS:-3072}"

# Qwen side uses smaller exp02 batch to avoid OOM.
EXP02_PER_DEVICE_TRAIN_BATCH_SIZE="${EXP02_PER_DEVICE_TRAIN_BATCH_SIZE:-4}"
EXP02_PER_DEVICE_EVAL_BATCH_SIZE="${EXP02_PER_DEVICE_EVAL_BATCH_SIZE:-2}"
EXP02_GRADIENT_ACCUMULATION_STEPS="${EXP02_GRADIENT_ACCUMULATION_STEPS:-2}"

MODEL_ID="${MODEL_ID}" \
MODEL_TAG="${MODEL_TAG}" \
TRAIN_CUDA_VISIBLE_DEVICES="${TRAIN_CUDA_VISIBLE_DEVICES}" \
INFER_CUDA_VISIBLE_DEVICES="${INFER_CUDA_VISIBLE_DEVICES}" \
INFER_NUM_SHARDS="${INFER_NUM_SHARDS}" \
RUN_BASE_DIR="${RUN_BASE_DIR}" \
EXP02_MAX_NEW_TOKENS="${EXP02_MAX_NEW_TOKENS}" \
EXP04_MAX_NEW_TOKENS="${EXP04_MAX_NEW_TOKENS}" \
EXP02_PER_DEVICE_TRAIN_BATCH_SIZE="${EXP02_PER_DEVICE_TRAIN_BATCH_SIZE}" \
EXP02_PER_DEVICE_EVAL_BATCH_SIZE="${EXP02_PER_DEVICE_EVAL_BATCH_SIZE}" \
EXP02_GRADIENT_ACCUMULATION_STEPS="${EXP02_GRADIENT_ACCUMULATION_STEPS}" \
bash "${ONE_MODEL_SH}"
